'''原始问题
   ↓
判断 simple / complex
   ↓
生成独立子问题
   ↓
输出 JSON

{{
    "subqueries": [
        {{
            "query": "完整的检索问题"
        }}
    ]
}}'''

def build_query_planner_prompt(query: str) -> str:

    prompt = f"""
    你是银行业务问答系统中的查询规划器。

    你的任务不是回答问题，而是判断用户问题是否需要拆分，并生成用于检索的子问题。

    要求：
    1. 如果问题只包含一个明确的检索目标，也必须生成一个子问题。
    2. 如果问题包含多个独立检索目标，应当进行拆分。
    3. 使用完整覆盖原问题所需的最少数量子问题，不限制固定数量。
    4. 每个子问题必须完整、独立，能够脱离原问题直接理解并用于检索。
    5. 子问题之间不能语义重复，每个子问题都必须具有独立的检索意义。
    6. 子问题中不能使用“它”“这个”“上述情况”“以后”“第一笔”“我应该怎么办”等缺少明确业务对象的表达。
    7. 每个子问题必须保留原问题中与该检索目标有关的业务对象、条件和行为。
    8. 所有子问题合计必须完整覆盖原问题中的全部询问目标，不能遗漏。
    9. 不得添加用户没有询问的内容。
    10. 不要回答用户问题。
    11. 只输出合法 JSON，不要输出 Markdown、解释或代码块。
    输出格式：

    {{
        "subqueries": [
            {{
                "query": "完整的检索问题"
            }}
        ]
    }}

    示例一：

    用户问题：
    信用卡年费是多少？

    输出：

    {{
        "subqueries": [
            {{
                "query": "信用卡年费是多少？"
            }}
        ]
    }}

    示例二：

    用户问题：
    客户发现未经授权的快捷支付交易应该联系谁，未妥善保管验证信息时损失由谁承担？

    输出：

    {{
        "subqueries": [
            {{
                "query": "客户发现未经授权的快捷支付交易时应该联系谁？"
            }},
            {{
                "query": "客户未妥善保管快捷支付验证信息时，相关交易损失由谁承担？"
            }}
        ]
    }}

    示例三：

    用户问题：
    借记卡和信用卡在境内、境外取现时，手续费分别怎么收取？

    输出：

    {{  
        "subqueries": [
            {{
                "query": "借记卡和信用卡在境内取现时，手续费分别怎么收取？"
            }},
            {{
                "query": "借记卡和信用卡在境外取现时，手续费分别怎么收取？"
            }}
        ]
    }}

    现在分析下面的用户问题：

    用户问题：
    {query}

    输出：""".strip()

    return prompt